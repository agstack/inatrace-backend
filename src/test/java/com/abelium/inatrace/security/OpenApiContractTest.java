/**
 * Exports the OpenAPI document generated by the running application and compares
 * it with the reviewed contract baseline. Set {@code -Dapi.contract.update=true}
 * explicitly to refresh that baseline locally.
 */
@SpringBootTest
@AutoConfigureMockMvc
@ActiveProfiles("test")
@Transactional
class OpenApiContractTest extends AbstractMySqlIntegrationTest {

    private static final Path BASELINE = Path.of("docs", "api-contract", "openapi.json");
    private static final Path ROUTE_INVENTORY = Path.of("docs", "api-auth-coverage", "routes.tsv");
    private static final Path EXPORT = Path.of("target", "api-contract", "openapi.json");
    private static final Path MANIFEST = Path.of("target", "api-contract", "manifest.json");
    private static final String NORMALIZATION_VERSION = "inatrace-openapi-v1";
    private static final String MANIFEST_SCHEMA_VERSION = "1";
    private static final int MAX_REPORTED_DIFFERENCES = 12;

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private ObjectMapper objectMapper;

    @TempDir
    Path temporaryDirectory;

    @Test
    void generatedOpenApiMatchesReviewedBaseline() throws Exception {
        var response = mockMvc.perform(get("/v3/api-docs")).andReturn().getResponse();
        assertEquals(200, response.getStatus(), "OpenAPI endpoint must answer successfully");
        String body = response.getContentAsString();
        assertFalse(body.isBlank(), "OpenAPI export must not be empty");

        JsonNode document = objectMapper.readTree(body);
        validateOpenApiDocument(document);
        assertEquals(inventoriedOperationCount(), openApiOperationCount(document.path("paths")),
                "OpenAPI operation count must match the reviewed Spring MVC route inventory");

        byte[] canonical = canonicalBytes(document);
        writeBuildArtifacts(canonical, document.path("openapi").asText());

        if (updateBaselineIfRequested(BASELINE, canonical, Boolean.getBoolean("api.contract.update"))) {
            return;
        }

        byte[] reviewed = reviewedBaseline(BASELINE);
        assertTrue(Arrays.equals(reviewed, canonical), () -> {
            try {
                return "OpenAPI contract differs from " + BASELINE + " at "
                        + String.join(", ", contractDifferences(objectMapper.readTree(reviewed),
                                objectMapper.readTree(canonical)))
                        + ". Review " + EXPORT + " and run with -Dapi.contract.update=true"
                        + " only for an accepted contract change.";
            } catch (IOException exception) {
                return "OpenAPI contract differs from " + BASELINE + ". Review " + EXPORT;
            }
        });
    }

    @Test
    void canonicalizationIsStableAndPreservesArrays() throws Exception {
        JsonNode source = objectMapper.readTree("""
                {"z":{"beta":2,"alpha":1},"array":[{"z":2,"a":1},"second"]}
                """);

        JsonNode normalized = normalize(source);
        assertEquals("alpha", normalized.path("z").fieldNames().next());
        assertEquals("second", normalized.path("array").get(1).asText());
        assertEquals(new String(canonicalBytes(normalized), StandardCharsets.UTF_8),
                new String(canonicalBytes(source), StandardCharsets.UTF_8));
    }

    @Test
    void canonicalizationRemovesOnlyTheEnvironmentSpecificRootServer() throws Exception {
        JsonNode localhost = objectMapper.readTree("""
                {"openapi":"3.0.1","servers":[{"url":"http://localhost:8080"}],"paths":{}}
                """);
        JsonNode remote = objectMapper.readTree("""
                {"openapi":"3.0.1","servers":[{"url":"https://api.example.test"}],"paths":{}}
                """);

        assertTrue(Arrays.equals(canonicalBytes(localhost), canonicalBytes(remote)),
                "The generated server origin is deployment metadata, not an API contract change");
    }

    @Test
    void canonicalizationRetainsContractFieldsForComparison() throws Exception {
        JsonNode original = objectMapper.readTree("""
                {"components":{"schemas":{"Plot":{"required":["name"],"properties":{"name":{"type":"string","enum":["A"]}}}}},"paths":{"/plots":{"get":{"operationId":"getPlots","responses":{"200":{"content":{"application/json":{}}}}}}}}
                """);
        JsonNode changed = objectMapper.readTree("""
                {"components":{"schemas":{"Plot":{"required":[],"properties":{"name":{"type":"number","enum":["B"]}}}}},"paths":{"/plots":{"get":{"operationId":"listPlots","responses":{"204":{"content":{"text/plain":{}}}}}}}}
                """);

        assertFalse(Arrays.equals(canonicalBytes(original), canonicalBytes(changed)),
                "Required fields, types, enums, operation IDs and response media types must remain visible");
        List<String> differences = contractDifferences(normalizeOpenApi(original), normalizeOpenApi(changed));
        assertTrue(differences.contains("/components/schemas/Plot/properties/name/type"));
        assertTrue(differences.contains("/components/schemas/Plot/properties/name/enum/0"));
        assertTrue(differences.contains("/paths/~1plots/get/operationId"));
        assertTrue(differences.contains("/paths/~1plots/get/responses/200"));

        JsonNode operationRemoved = objectMapper.readTree("""
                {"components":{"schemas":{"Plot":{"required":["name"],"properties":{"name":{"type":"string","enum":["A"]}}}}},"paths":{"/plots":{}}}
                """);
        assertTrue(contractDifferences(normalizeOpenApi(original), normalizeOpenApi(operationRemoved))
                .contains("/paths/~1plots/get"), "Removing an operation must remain visible to the comparison");
    }

    @Test
    void validationRejectsAnIncompleteDocumentAndInvalidManifest() throws Exception {
        assertThrows(IllegalStateException.class,
                () -> validateOpenApiDocument(objectMapper.readTree("{\"openapi\":\"3.0.1\"}")));

        byte[] canonical = canonicalBytes(objectMapper.readTree("""
                {"openapi":"3.0.1","paths":{"/health":{"get":{"responses":{"200":{}}}}}}
                """));
        SourceProvenance provenance = new SourceProvenance("example/backend", "revision", "clean", null);
        ObjectNode manifest = manifestFor(canonical, "3.0.1", provenance);
        validateManifest(manifest, canonical, provenance);

        ObjectNode invalidHash = manifest.deepCopy();
        invalidHash.put("spec_sha256", "not-the-spec-hash");
        assertThrows(IllegalStateException.class, () -> validateManifest(invalidHash, canonical, provenance));

        ObjectNode invalidRevision = manifest.deepCopy();
        invalidRevision.put("source_revision", "another-revision");
        assertThrows(IllegalStateException.class, () -> validateManifest(invalidRevision, canonical, provenance));

        ObjectNode invalidNormalization = manifest.deepCopy();
        invalidNormalization.put("normalization_version", "unknown-v2");
        assertThrows(IllegalStateException.class, () -> validateManifest(invalidNormalization, canonical, provenance));
    }

    @Test
    void dirtyTreeDigestIncludesTrackedAndUntrackedContentDeterministically() {
        Map<String, byte[]> firstOrder = Map.of(
                "docs/api-contract/openapi.json", "first".getBytes(StandardCharsets.UTF_8),
                "src/test/OpenApiContractTest.java", "second".getBytes(StandardCharsets.UTF_8));
        Map<String, byte[]> reverseOrder = Map.of(
                "src/test/OpenApiContractTest.java", "second".getBytes(StandardCharsets.UTF_8),
                "docs/api-contract/openapi.json", "first".getBytes(StandardCharsets.UTF_8));

        String digest = sourceTreeDigest("tracked diff".getBytes(StandardCharsets.UTF_8), firstOrder);
        assertEquals(digest, sourceTreeDigest("tracked diff".getBytes(StandardCharsets.UTF_8), reverseOrder));
        assertFalse(digest.equals(sourceTreeDigest("tracked diff changed".getBytes(StandardCharsets.UTF_8), firstOrder)));
        assertFalse(digest.equals(sourceTreeDigest("tracked diff".getBytes(StandardCharsets.UTF_8), Map.of(
                "docs/api-contract/openapi.json", "changed".getBytes(StandardCharsets.UTF_8),
                "src/test/OpenApiContractTest.java", "second".getBytes(StandardCharsets.UTF_8)))));
    }

    @Test
    void baselineUpdateIsExplicitAndNormalComparisonLeavesItUntouched() throws Exception {
        Path baseline = temporaryDirectory.resolve("openapi.json");
        byte[] reviewed = "reviewed\n".getBytes(StandardCharsets.UTF_8);
        byte[] candidate = "candidate\n".getBytes(StandardCharsets.UTF_8);
        Files.write(baseline, reviewed);

        assertFalse(updateBaselineIfRequested(baseline, candidate, false));
        assertTrue(Arrays.equals(reviewed, Files.readAllBytes(baseline)),
                "Normal comparison mode must not rewrite the reviewed baseline");
        assertTrue(updateBaselineIfRequested(baseline, candidate, true));
        assertTrue(Arrays.equals(candidate, Files.readAllBytes(baseline)));
    }

    static JsonNode normalize(JsonNode source) {
        if (source.isObject()) {
            ObjectNode normalized = JsonNodeFactory.instance.objectNode();
            Map<String, JsonNode> fields = new TreeMap<>();
            Iterator<Map.Entry<String, JsonNode>> iterator = source.fields();
            iterator.forEachRemaining(entry -> fields.put(entry.getKey(), entry.getValue()));
            fields.forEach((name, value) -> normalized.set(name, normalize(value)));
            return normalized;
        }
        if (source.isArray()) {
            ArrayNode normalized = JsonNodeFactory.instance.arrayNode();
            source.forEach(value -> normalized.add(normalize(value)));
            return normalized;
        }
        return source.deepCopy();
    }

    static JsonNode normalizeOpenApi(JsonNode source) {
        JsonNode normalized = normalize(source);
        if (normalized instanceof ObjectNode object) {
            object.remove("servers");
        }
        return normalized;
    }

    static List<String> contractDifferences(JsonNode expected, JsonNode actual) {
        List<String> differences = new ArrayList<>();
        collectDifferences(expected, actual, "", differences);
        return differences.isEmpty() ? List.of("<byte representation differs>") : differences;
    }

    private static void collectDifferences(JsonNode expected, JsonNode actual, String path, List<String> differences) {
        if (differences.size() >= MAX_REPORTED_DIFFERENCES) {
            return;
        }
        if (expected == null || actual == null || expected.getNodeType() != actual.getNodeType()) {
            differences.add(displayPath(path));
            return;
        }
        if (expected.isObject()) {
            TreeSet<String> names = new TreeSet<>();
            expected.fieldNames().forEachRemaining(names::add);
            actual.fieldNames().forEachRemaining(names::add);
            for (String name : names) {
                collectDifferences(expected.get(name), actual.get(name), path + "/" + escapePointer(name), differences);
            }
            return;
        }
        if (expected.isArray()) {
            if (expected.size() != actual.size()) {
                differences.add(displayPath(path));
            }
            for (int index = 0; index < Math.min(expected.size(), actual.size()); index++) {
                collectDifferences(expected.get(index), actual.get(index), path + "/" + index, differences);
            }
            return;
        }
        if (!expected.equals(actual)) {
            differences.add(displayPath(path));
        }
    }

    private static String escapePointer(String value) {
        return value.replace("~", "~0").replace("/", "~1");
    }

    private static String displayPath(String path) {
        return path.isBlank() ? "/" : path;
    }

    private static void validateOpenApiDocument(JsonNode document) {
        if (!document.isObject() || document.path("openapi").asText().isBlank()
                || !document.path("paths").isObject() || document.path("paths").isEmpty()) {
            throw new IllegalStateException("Generated OpenAPI document is incomplete or invalid");
        }
    }

    private static int openApiOperationCount(JsonNode paths) {
        int count = 0;
        Iterator<JsonNode> entries = paths.elements();
        while (entries.hasNext()) {
            Iterator<String> methods = entries.next().fieldNames();
            while (methods.hasNext()) {
                if (Set.of("get", "post", "put", "patch", "delete", "head", "options", "trace")
                        .contains(methods.next())) {
                    count++;
                }
            }
        }
        return count;
    }

    private static int inventoriedOperationCount() throws IOException {
        try (var routes = Files.lines(ROUTE_INVENTORY)) {
            return (int) routes.filter(line -> !line.isBlank() && !line.startsWith("#")).count();
        }
    }

    private byte[] canonicalBytes(JsonNode document) throws IOException {
        ObjectMapper canonicalMapper = objectMapper.copy()
                .enable(SerializationFeature.ORDER_MAP_ENTRIES_BY_KEYS);
        String json = canonicalMapper.writerWithDefaultPrettyPrinter()
                .writeValueAsString(normalizeOpenApi(document));
        return (json.replace("\r\n", "\n").replace('\r', '\n').stripTrailing() + "\n")
                .getBytes(StandardCharsets.UTF_8);
    }

    private void writeBuildArtifacts(byte[] canonical, String openApiVersion) throws Exception {
        Files.createDirectories(EXPORT.getParent());
        Files.write(EXPORT, canonical);

        SourceProvenance provenance = sourceProvenance();
        ObjectNode manifest = manifestFor(canonical, openApiVersion, provenance);
        Files.writeString(MANIFEST, objectMapper.writerWithDefaultPrettyPrinter()
                .writeValueAsString(manifest).replace("\r\n", "\n").replace('\r', '\n').stripTrailing() + "\n",
                StandardCharsets.UTF_8);
        validateManifest(objectMapper.readTree(Files.readAllBytes(MANIFEST)), canonical, provenance);
    }

    private ObjectNode manifestFor(byte[] canonical, String openApiVersion, SourceProvenance provenance) {
        ObjectNode manifest = JsonNodeFactory.instance.objectNode();
        manifest.put("schema_version", Integer.parseInt(MANIFEST_SCHEMA_VERSION));
        manifest.put("repository", provenance.repository());
        manifest.put("source_revision", provenance.revision());
        manifest.put("source_state", provenance.state());
        if (provenance.treeDigest() != null) {
            manifest.put("source_tree_digest", provenance.treeDigest());
            manifest.put("source_tree_digest_method",
                    "sha256(git diff --binary HEAD + sorted untracked path/content SHA-256)");
        }
        manifest.put("spec_file", EXPORT.getFileName().toString());
        manifest.put("spec_sha256", sha256(canonical));
        manifest.put("openapi_version", openApiVersion);
        manifest.put("normalization_version", NORMALIZATION_VERSION);
        ObjectNode runtime = manifest.putObject("runtime");
        runtime.put("java", System.getProperty("java.version"));
        runtime.put("springdoc", springdocVersionFromBuild());
        return manifest;
    }

    private static void validateManifest(JsonNode manifest, byte[] canonical, SourceProvenance provenance) {
        requireEquals("schema_version", MANIFEST_SCHEMA_VERSION, manifest.path("schema_version").asText());
        requireEquals("repository", provenance.repository(), requiredText(manifest, "repository"));
        requireEquals("source_revision", provenance.revision(), requiredText(manifest, "source_revision"));
        requireEquals("source_state", provenance.state(), requiredText(manifest, "source_state"));
        requireEquals("spec_file", EXPORT.getFileName().toString(), requiredText(manifest, "spec_file"));
        requireEquals("spec_sha256", sha256(canonical), requiredText(manifest, "spec_sha256"));
        requireEquals("normalization_version", NORMALIZATION_VERSION, requiredText(manifest, "normalization_version"));
        requiredText(manifest, "openapi_version");
        requiredText(manifest.path("runtime"), "java");
        requiredText(manifest.path("runtime"), "springdoc");
        if ("dirty".equals(provenance.state())) {
            requireEquals("source_tree_digest", provenance.treeDigest(), requiredText(manifest, "source_tree_digest"));
            requiredText(manifest, "source_tree_digest_method");
        } else if (manifest.has("source_tree_digest")) {
            throw new IllegalStateException("Clean contract manifest must not claim a dirty-tree digest");
        }
    }

    private static String requiredText(JsonNode object, String field) {
        String value = object.path(field).asText();
        if (value.isBlank()) {
            throw new IllegalStateException("Contract manifest is missing " + field);
        }
        return value;
    }

    private static void requireEquals(String field, String expected, String actual) {
        if (!expected.equals(actual)) {
            throw new IllegalStateException("Contract manifest " + field + " does not match the generated artifact");
        }
    }

    private static byte[] reviewedBaseline(Path baseline) throws IOException {
        if (!Files.isRegularFile(baseline)) {
            throw new IllegalStateException("Missing reviewed API contract baseline: run with -Dapi.contract.update=true and review the diff");
        }
        return Files.readAllBytes(baseline);
    }

    private static boolean updateBaselineIfRequested(Path baseline, byte[] canonical, boolean update) throws IOException {
        if (!update) {
            return false;
        }
        Files.createDirectories(baseline.getParent());
        Files.write(baseline, canonical);
        return true;
    }

    private static SourceProvenance sourceProvenance() {
        String state = sourceState();
        return new SourceProvenance(repositoryIdentity(), git("rev-parse", "HEAD"), state,
                "dirty".equals(state) ? dirtyTreeDigest() : null);
    }

    private static String repositoryIdentity() {
        String remote = git("config", "--get", "remote.origin.url");
        if (remote.endsWith(".git")) {
            remote = remote.substring(0, remote.length() - 4);
        }
        if (remote.startsWith("git@github.com:")) {
            return remote.substring("git@github.com:".length());
        }
        if (remote.startsWith("https://github.com/")) {
            return remote.substring("https://github.com/".length());
        }
        return remote.isBlank() ? "unknown" : remote;
    }

    private static String sourceState() {
        return git("status", "--porcelain").isBlank() ? "clean" : "dirty";
    }

    private static String dirtyTreeDigest() {
        Map<String, byte[]> untracked = new TreeMap<>();
        for (String path : gitNullSeparated("ls-files", "--others", "--exclude-standard", "-z")) {
            Path candidate = Path.of(path).normalize();
            if (candidate.isAbsolute() || candidate.startsWith("..") || !Files.isRegularFile(candidate)) {
                throw new IllegalStateException("Cannot include untracked path in contract provenance: " + path);
            }
            try {
                untracked.put(path, Files.readAllBytes(candidate));
            } catch (IOException exception) {
                throw new IllegalStateException("Cannot read untracked path for contract provenance: " + path, exception);
            }
        }
        return sourceTreeDigest(gitBytes("diff", "--binary", "HEAD"), untracked);
    }

    static String sourceTreeDigest(byte[] trackedDiff, Map<String, byte[]> untracked) {
        try {
            ByteArrayOutputStream source = new ByteArrayOutputStream();
            source.write("tracked\0".getBytes(StandardCharsets.UTF_8));
            source.write(trackedDiff);
            for (Map.Entry<String, byte[]> entry : new TreeMap<>(untracked).entrySet()) {
                source.write("untracked\0".getBytes(StandardCharsets.UTF_8));
                source.write(entry.getKey().getBytes(StandardCharsets.UTF_8));
                source.write(0);
                source.write(sha256(entry.getValue()).getBytes(StandardCharsets.UTF_8));
                source.write(0);
            }
            return sha256(source.toByteArray());
        } catch (IOException exception) {
            throw new IllegalStateException("Cannot calculate contract provenance digest", exception);
        }
    }

    private static String springdocVersionFromBuild() {
        try {
            String pom = Files.readString(Path.of("pom.xml"), StandardCharsets.UTF_8);
            Matcher matcher = Pattern.compile("<artifactId>springdoc-openapi-starter-webmvc-ui</artifactId>\\s*<version>([^<]+)</version>")
                    .matcher(pom);
            if (matcher.find()) {
                return matcher.group(1).trim();
            }
        } catch (IOException exception) {
            throw new IllegalStateException("Cannot read the springdoc version from pom.xml", exception);
        }
        throw new IllegalStateException("pom.xml does not declare springdoc-openapi-starter-webmvc-ui with a version");
    }

    private static String git(String... arguments) {
        try {
            Process process = gitProcess(arguments);
            String output = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8).trim();
            return process.waitFor() == 0 ? output : "unknown";
        } catch (InterruptedException exception) {
            Thread.currentThread().interrupt();
            return "unknown";
        } catch (IOException exception) {
            return "unknown";
        }
    }

    private static byte[] gitBytes(String... arguments) {
        try {
            Process process = gitProcess(arguments);
            byte[] output = process.getInputStream().readAllBytes();
            if (process.waitFor() != 0) {
                throw new IllegalStateException("git command failed while creating contract provenance");
            }
            return output;
        } catch (InterruptedException exception) {
            Thread.currentThread().interrupt();
            throw new IllegalStateException("Interrupted while creating contract provenance", exception);
        } catch (IOException exception) {
            throw new IllegalStateException("Cannot run git while creating contract provenance", exception);
        }
    }

    private static List<String> gitNullSeparated(String... arguments) {
        String output = new String(gitBytes(arguments), StandardCharsets.UTF_8);
        List<String> values = new ArrayList<>();
        int start = 0;
        for (int end = output.indexOf('\0'); end >= 0; end = output.indexOf('\0', start)) {
            String value = output.substring(start, end);
            if (!value.isEmpty()) {
                values.add(value);
            }
            start = end + 1;
        }
        String finalValue = output.substring(start);
        if (!finalValue.isEmpty()) {
            values.add(finalValue);
        }
        return values;
    }

    private static Process gitProcess(String... arguments) throws IOException {
        String[] command = new String[arguments.length + 1];
        command[0] = "git";
        System.arraycopy(arguments, 0, command, 1, arguments.length);
        return new ProcessBuilder(command).redirectErrorStream(true).start();
    }

    private static String sha256(byte[] value) {
        try {
            byte[] hash = MessageDigest.getInstance("SHA-256").digest(value);
            StringBuilder hexadecimal = new StringBuilder(hash.length * 2);
            for (byte current : hash) {
                hexadecimal.append(String.format("%02x", current));
            }
            return hexadecimal.toString();
        } catch (NoSuchAlgorithmException exception) {
            throw new IllegalStateException("SHA-256 must be available", exception);
        }
    }

    private record SourceProvenance(String repository, String revision, String state, String treeDigest) {
    }
}
